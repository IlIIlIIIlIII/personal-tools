#!/usr/bin/env python3
"""Generate GTK and Shell palettes from the approved, shared design tokens."""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[2]
DESIGN = ROOT / 'Sources/Linux/Design'
tokens = json.loads((DESIGN / 'tokens.json').read_text())
variables = {**tokens['colors'], **tokens['layout']}
def flatten(value, prefix=''):
    for key, content in value.items():
        name=f'{prefix}.{key}' if prefix else key
        if isinstance(content,dict): yield from flatten(content,name)
        elif not isinstance(content,list): yield name,content
variables.update(flatten(tokens))
for kind, filename in [('App', 'style'), ('Shell', 'styles-base')]:
    base = ROOT / f'Sources/Linux/{kind}/{filename}.css.in'
    if not base.exists():
        base = ROOT / f'Sources/Linux/{kind}/{filename}.css'
    if not base.exists():
        continue
    value = base.read_text()
    for key, content in variables.items():
        value = value.replace('{{' + key + '}}', str(content))
    if '{{' in value:
        raise ValueError(f'Unresolved design token in {base}')
    target = ROOT / f'Sources/Linux/{kind}/' / ('style.css' if kind == 'App' else 'stylesheet.css')
    target.write_text('/* Generated by Scripts/Linux/generate-design.py. */\n' + value)
    light = base.read_text()
    for key, content in {**variables, **tokens['light']}.items():
        light = light.replace('{{' + key + '}}', str(content))
    if kind == 'Shell':
        # Added specificity survives Shell loading the base extension stylesheet later.
        light = re.sub(r'([^{}]+)\{', lambda m: ', '.join(variant for selector in m[1].split(',') for variant in ('.pt-light' + selector.strip(), '.pt-light ' + selector.strip())) + ' {', light)
    (target.parent / ('style-light.css' if kind == 'App' else 'stylesheet-light.css')).write_text('/* Generated from shared light tokens. */\n' + light)
print('Generated available GTK/Shell styles from design tokens.')
